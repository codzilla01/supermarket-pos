  let lang = DEFAULT_LANG;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) lang = saved;
  } catch { /* storage may be blocked */ }

  const listeners = new Set();

  function interpolate(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, (m, key) => (key in vars ? String(vars[key]) : m));
  }

  function t(key, vars) {
    const table = MESSAGES[lang] || MESSAGES[DEFAULT_LANG];
    const fallback = MESSAGES.en[key] ?? key;
    return interpolate(table[key] ?? fallback, vars);
  }

  function apply(root = document) {
    const el = root === document ? document : root;
    if (root === document || root === document.documentElement) {
      document.documentElement.lang = lang;
      document.documentElement.dir = DIRS[lang];
    }
    el.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    el.querySelectorAll('[data-i18n-html]').forEach(node => { node.innerHTML = t(node.dataset.i18nHtml); });
    el.querySelectorAll('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
    el.querySelectorAll('[data-i18n-title]').forEach(node => { node.title = t(node.dataset.i18nTitle); });
    el.querySelectorAll('[data-i18n-aria-label]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel)); });
    document.dispatchEvent(new CustomEvent('i18n:applied', { detail: { lang } }));
  }

  function setLang(next) {
    const target = SUPPORTED.includes(next) ? next : DEFAULT_LANG;
    lang = target;
    try { localStorage.setItem(STORAGE_KEY, target); } catch { /* ignore quota/private mode */ }
    apply(document);
    listeners.forEach(fn => { try { fn(target); } catch { /* keep other listeners alive */ } });
    return lang;
  }

  function toggle() { return setLang(lang === 'ar' ? 'en' : 'ar'); }
  function locale() { return LOCALES[lang] || LOCALES.en; }
  function dir() { return DIRS[lang]; }
  function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

  const api = { t, setLang, toggle, apply, onChange, locale, dir, SUPPORTED, categoryLabel, categoryCanonical, unitLabel, unitCanonical, get lang() { return lang; } };
  window.I18N = api;
